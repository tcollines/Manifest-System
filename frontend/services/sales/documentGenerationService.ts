import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { BusinessDocument } from './financialStatementService';

export const documentGenerationService = {
  generatePDF(docRecord: BusinessDocument): jsPDF {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.width;
    
    // 1. Add Header (Logo/Church Name)
    doc.setFontSize(20);
    doc.setFont('helvetica', 'bold');
    doc.text('MANIFEST', pageWidth / 2, 20, { align: 'center' });
    
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 100, 100);
    doc.text('Financial & Operational Reporting System', pageWidth / 2, 26, { align: 'center' });
    
    // 2. Add Report Details
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text(docRecord.document_name, 14, 40);
    
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Report Type: ${docRecord.report_type}`, 14, 48);
    doc.text(`Period: ${docRecord.date_range}`, 14, 54);
    doc.text(`Generated By: ${docRecord.generated_by_name}`, 14, 60);
    doc.text(`Date: ${new Date(docRecord.created_at).toLocaleString()}`, 14, 66);
    
    doc.setDrawColor(200, 200, 200);
    doc.line(14, 70, pageWidth - 14, 70);

    // 3. Render Data based on Report Type
    let startY = 80;
    
    if (docRecord.report_type === 'Profit & Loss Statement' || docRecord.report_type === 'Sales Report') {
        const data = docRecord.report_data;
        autoTable(doc, {
            startY,
            head: [['Metric', 'Amount (UGX)']],
            body: [
                ['Total Sales Revenue', Number(data.totalSales || 0).toLocaleString()],
                ['Cost of Goods Sold (Est)', Number((data.totalSales || 0) - (data.totalProfit || 0)).toLocaleString()],
                ['Gross Profit', Number(data.totalProfit || 0).toLocaleString()],
                ['Total Orders Completed', data.completedOrdersCount?.toString() || '0'],
            ],
            theme: 'striped',
            headStyles: { fillColor: [41, 128, 185] },
        });
    } 
    else if (docRecord.report_type === 'Inventory Valuation Report') {
        const data = docRecord.report_data;
        
        // Summary
        doc.text(`Total Cost Value: UGX ${Number(data.totalCostValue || 0).toLocaleString()}`, 14, startY);
        doc.text(`Total Retail Value: UGX ${Number(data.totalRetailValue || 0).toLocaleString()}`, 14, startY + 6);
        startY += 12;

        const tableBody = (data.items || []).map((item: any) => [
            item.productName,
            item.variantName,
            item.stockQuantity.toString(),
            Number(item.costPrice).toLocaleString(),
            Number(item.inventoryCostValue).toLocaleString()
        ]);

        autoTable(doc, {
            startY,
            head: [['Product', 'Variant', 'Qty', 'Unit Cost', 'Total Cost']],
            body: tableBody,
            theme: 'grid',
            headStyles: { fillColor: [41, 128, 185] },
        });
    }
    else if (docRecord.report_type === 'Cash Position Report' || docRecord.report_type === 'Balance Sheet') {
        const data = docRecord.report_data;
        autoTable(doc, {
            startY,
            head: [['Account/Metric', 'Balance (UGX)']],
            body: [
                ['Cash at Hand', Number(data.cashAtHand || 0).toLocaleString()],
                ['Outstanding Receivables', Number(data.outstandingBalances || 0).toLocaleString()],
                ['Supplier Payables', Number(data.supplierPayables || 0).toLocaleString()],
                ['Inventory Asset Value', Number(data.inventoryCostValue || 0).toLocaleString()],
                ['Gross Profit (All-Time)', Number(data.grossProfit || 0).toLocaleString()],
            ],
            theme: 'striped',
            headStyles: { fillColor: [41, 128, 185] },
        });
    } else {
        doc.text('Detailed rendering for this report type is not fully configured yet.', 14, startY);
        doc.text('Raw Data Snapshot:', 14, startY + 10);
        doc.setFont('courier', 'normal');
        doc.setFontSize(8);
        const splitText = doc.splitTextToSize(JSON.stringify(docRecord.report_data, null, 2), pageWidth - 28);
        doc.text(splitText, 14, startY + 18);
    }

    // 4. Footer & Signature Lines
    const finalY = (doc as any).lastAutoTable ? (doc as any).lastAutoTable.finalY + 20 : startY + 60;
    
    if (finalY > doc.internal.pageSize.height - 40) {
        doc.addPage();
    }
    
    const sigY = (doc as any).lastAutoTable && finalY > doc.internal.pageSize.height - 40 ? 40 : finalY;
    
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text('Prepared By:', 14, sigY);
    doc.line(14, sigY + 10, 70, sigY + 10);
    doc.text(docRecord.generated_by_name || 'Finance Officer', 14, sigY + 15);
    
    doc.text('Approved By:', pageWidth - 70, sigY);
    doc.line(pageWidth - 70, sigY + 10, pageWidth - 14, sigY + 10);
    doc.text('Head of Finance / Admin', pageWidth - 70, sigY + 15);

    // Page numbers
    const pageCount = doc.getNumberOfPages();
    for(let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(8);
        doc.setTextColor(150);
        doc.text(`Page ${i} of ${pageCount}`, pageWidth / 2, doc.internal.pageSize.height - 10, { align: 'center' });
    }

    return doc;
  }
};

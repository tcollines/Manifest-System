import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { BusinessDocument } from './financialStatementService';

export const documentGenerationService = {
  async generatePDF(docRecord: BusinessDocument): Promise<jsPDF> {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.width;
    
    // 1. Add Header (Logo/Church Name)
    let textStartX = 14;
    try {
        const logoBase64 = await new Promise<string>((resolve, reject) => {
            const img = new Image();
            img.crossOrigin = "Anonymous";
            img.onload = () => {
                const canvas = document.createElement('canvas');
                canvas.width = img.width;
                canvas.height = img.height;
                const ctx = canvas.getContext('2d');
                if (ctx) {
                    const radius = img.width * 0.15;
                    ctx.beginPath();
                    ctx.moveTo(radius, 0);
                    ctx.lineTo(img.width - radius, 0);
                    ctx.quadraticCurveTo(img.width, 0, img.width, radius);
                    ctx.lineTo(img.width, img.height - radius);
                    ctx.quadraticCurveTo(img.width, img.height, img.width - radius, img.height);
                    ctx.lineTo(radius, img.height);
                    ctx.quadraticCurveTo(0, img.height, 0, img.height - radius);
                    ctx.lineTo(0, radius);
                    ctx.quadraticCurveTo(0, 0, radius, 0);
                    ctx.closePath();
                    ctx.clip();
                    ctx.drawImage(img, 0, 0);
                    resolve(canvas.toDataURL('image/png'));
                } else {
                    reject('No context');
                }
            };
            img.onerror = reject;
            img.src = '/MANIFEST.png';
        });
        
        doc.addImage(logoBase64, 'PNG', 14, 10, 18, 18);
        textStartX = 38; // 14 (margin) + 18 (logo) + 6 (padding)
    } catch (e) {
        console.warn("Failed to load PDF logo", e);
    }
    
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('MANIFEST', textStartX, 18);
    
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 100, 100);
    doc.text('Financial & Operational Reporting System', textStartX, 24);
    
    // 2. Add Report Title
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    doc.text(docRecord.document_name.toUpperCase(), pageWidth / 2, 45, { align: 'center' });
    
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    const asAtDate = docRecord.date_range === 'All Time' ? new Date(docRecord.created_at).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : docRecord.date_range;
    doc.text(`As At ${asAtDate}`, pageWidth / 2, 51, { align: 'center' });
    
    // 3. Add Report Metadata
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(80, 80, 80);
    doc.text(`Report Type: ${docRecord.report_type}`, 14, 61);
    doc.text(`Period: As At ${asAtDate}`, 14, 67);
    doc.text(`Generated By: ${docRecord.generated_by_name || 'System'}`, 14, 73);
    
    const dateGenerated = new Date(docRecord.created_at);
    const dateFormatted = `${dateGenerated.getDate().toString().padStart(2, '0')}/${(dateGenerated.getMonth() + 1).toString().padStart(2, '0')}/${dateGenerated.getFullYear()} ${dateGenerated.getHours().toString().padStart(2, '0')}:${dateGenerated.getMinutes().toString().padStart(2, '0')}`;
    doc.text(`Date Generated: ${dateFormatted}`, 14, 79);
    
    doc.setDrawColor(200, 200, 200);
    doc.setLineWidth(0.5);
    doc.line(14, 84, pageWidth - 14, 84);

    // 4. Render Data based on Report Type
    let startY = 93;
    
    if (docRecord.report_type === 'Profit & Loss Statement' || docRecord.report_type === 'Income Statement') {
        const data = docRecord.report_data || {};
        const rev = data.revenue || { merchRevenue: 0, eventRevenue: 0, otherRevenue: 0, totalRevenue: 0 };
        const cogs = data.cogs || { inventoryCogs: 0, procurementCogs: 0, totalCogs: 0 };
        const ops = data.operatingExpenses || { transport: 0, packaging: 0, printing: 0, eventSetup: 0, salaries: 0, utilities: 0, miscellaneous: 0, totalExpenses: 0 };
        const grossProfit = data.grossProfit || 0;
        const netProfit = data.netProfit || 0;

        // REVENUE SECTION
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.setTextColor(0, 0, 0); doc.text('REVENUE', 14, startY); startY += 2;
        autoTable(doc, {
            startY, head: [['Revenue Item', 'Amount (UGX)']],
            body: [
                ['Merchandise Sales Revenue', rev.merchRevenue.toLocaleString()],
                ['Event Sales Revenue', rev.eventRevenue.toLocaleString()],
                ['Other Revenue', rev.otherRevenue.toLocaleString()]
            ],
            foot: [['Total Revenue', rev.totalRevenue.toLocaleString()]],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 } }, columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;

        // COGS SECTION
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('COST OF GOODS SOLD', 14, startY); startY += 2;
        autoTable(doc, {
            startY, head: [['Cost Item', 'Amount (UGX)']],
            body: [
                ['Inventory Cost of Sold Items', cogs.inventoryCogs.toLocaleString()],
                ['Procurement Cost Allocations', cogs.procurementCogs.toLocaleString()]
            ],
            foot: [['Total Cost of Goods Sold', cogs.totalCogs.toLocaleString()]],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 } }, columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;

        // GROSS PROFIT SUMMARY
        autoTable(doc, {
            startY, body: [['Gross Profit', grossProfit.toLocaleString()]],
            theme: 'plain', bodyStyles: { fontStyle: 'bold', cellPadding: 4, textColor: 0, fillColor: [230, 245, 230] }, columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;

        // OPERATING EXPENSES SECTION
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('OPERATING EXPENSES', 14, startY); startY += 2;
        autoTable(doc, {
            startY, head: [['Expense Category', 'Amount (UGX)']],
            body: [
                ['Transport (Placeholder)', ops.transport.toLocaleString()],
                ['Packaging (Placeholder)', ops.packaging.toLocaleString()],
                ['Printing (Placeholder)', ops.printing.toLocaleString()],
                ['Event Setup (Placeholder)', ops.eventSetup.toLocaleString()],
                ['Salaries (Placeholder)', ops.salaries.toLocaleString()],
                ['Utilities (Placeholder)', ops.utilities.toLocaleString()],
                ['Miscellaneous Expenses (Placeholder)', ops.miscellaneous.toLocaleString()]
            ],
            foot: [['Total Operating Expenses', ops.totalExpenses.toLocaleString()]],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 } }, columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;

        // NET PROFIT SUMMARY
        autoTable(doc, {
            startY, body: [['Net Profit / Surplus', netProfit.toLocaleString()]],
            theme: 'plain', bodyStyles: { fontStyle: 'bold', cellPadding: 6, fontSize: 12, textColor: 0, fillColor: [220, 240, 255] }, columnStyles: { 1: { halign: 'right' } }
        });
    }
    else if (docRecord.report_type === 'Cash Position Report') {
        const data = docRecord.report_data || {};
        const cashbook = data.cashbook || [];
        
        let totalIn = 0, totalOut = 0;
        const tableBody = cashbook.map((t: any) => {
            totalIn += Number(t.moneyIn);
            totalOut += Number(t.moneyOut);
            return [
                new Date(t.date).toLocaleDateString('en-GB'),
                t.reference,
                t.description,
                t.method,
                Number(t.moneyIn) > 0 ? Number(t.moneyIn).toLocaleString() : '-',
                Number(t.moneyOut) > 0 ? Number(t.moneyOut).toLocaleString() : '-',
                Number(t.runningBalance).toLocaleString()
            ];
        });

        autoTable(doc, {
            startY,
            head: [['Date', 'Ref', 'Description', 'Method', 'Money In', 'Money Out', 'Balance']],
            body: tableBody,
            foot: [['', '', 'TOTALS', '', totalIn.toLocaleString(), totalOut.toLocaleString(), (totalIn - totalOut).toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            bodyStyles: { cellPadding: 2, fontSize: 9 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 1 }, lineColor: [0, 0, 0] },
            columnStyles: { 4: { halign: 'right' }, 5: { halign: 'right' }, 6: { halign: 'right' } }
        });
    }
    else if (docRecord.report_type === 'Inventory Valuation Report') {
        const data = docRecord.report_data || {};
        
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('INVENTORY VALUATION', 14, startY); startY += 2;
        const tableBody = (data.items || []).map((item: any) => [
            item.productName,
            item.variantName,
            item.stockQuantity.toString(),
            Number(item.costPrice).toLocaleString(),
            Number(item.sellingPrice).toLocaleString(),
            Number(item.inventoryCostValue).toLocaleString(),
            Number(item.inventoryRetailValue).toLocaleString()
        ]);

        autoTable(doc, {
            startY,
            head: [['Product', 'Variant', 'Qty', 'Unit Cost', 'Unit Retail', 'Cost Value', 'Retail Value']],
            body: tableBody,
            foot: [['', '', 'TOTALS', '', '', Number(data.totalCostValue || 0).toLocaleString(), Number(data.totalRetailValue || 0).toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
            bodyStyles: { fontSize: 8 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 2, lineWidth: { top: 1, bottom: 1 }, lineColor: [0, 0, 0] },
            columnStyles: { 2: { halign: 'center' }, 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' }, 6: { halign: 'right' } }
        });
    }
    else if (docRecord.report_type === 'Supplier Ledger') {
        const data = docRecord.report_data || {};
        const txs = data.transactions || [];
        
        doc.setFontSize(10);
        doc.setFont('helvetica', 'bold');
        doc.text(`Supplier Name: All Suppliers (Aggregated)`, 14, startY);
        doc.text(`Statement Period: ${docRecord.date_range}`, 14, startY + 5);
        doc.text(`Outstanding Balance: UGX ${Number(data.totalOutstanding || 0).toLocaleString()}`, 14, startY + 10);
        startY += 15;

        let totalDebit = 0, totalCredit = 0;
        const tableBody = txs.map((t: any) => {
            totalDebit += Number(t.debit);
            totalCredit += Number(t.credit);
            return [
                new Date(t.date).toLocaleDateString('en-GB'),
                t.reference,
                t.description,
                Number(t.debit) > 0 ? Number(t.debit).toLocaleString() : '-',
                Number(t.credit) > 0 ? Number(t.credit).toLocaleString() : '-',
                Number(t.runningBalance).toLocaleString()
            ];
        });

        autoTable(doc, {
            startY,
            head: [['Date', 'Ref No', 'Description', 'Debit (UGX)', 'Credit (UGX)', 'Balance']],
            body: tableBody,
            foot: [['', '', 'TOTALS', totalDebit.toLocaleString(), totalCredit.toLocaleString(), (totalDebit - totalCredit).toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 } },
            bodyStyles: { cellPadding: 2, fontSize: 9 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 1 }, lineColor: [0, 0, 0] },
            columnStyles: { 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' } }
        });
    }
    else if (docRecord.report_type === 'Sales Report' || docRecord.report_type === 'Sales & Inventory Summary') {
        const data = docRecord.report_data || {};
        
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('SALES SUMMARY', 14, startY); startY += 2;
        autoTable(doc, {
            startY,
            head: [['Metric', 'Value']],
            body: [
                ['Total Orders', Number(data.totalOrders || 0).toLocaleString()],
                ['Completed Sales', Number(data.completedSales || 0).toLocaleString()],
                ['Unpaid Orders', Number(data.unpaidOrders || 0).toLocaleString()],
                ['Total Revenue', `UGX ${Number(data.totalRevenue || 0).toLocaleString()}`],
                ['Average Order Value', `UGX ${Number(data.avgOrderValue || 0).toLocaleString()}`]
            ],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
            columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;
        
        if (data.categories && data.categories.length > 0) {
            doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('CATEGORY PERFORMANCE', 14, startY); startY += 2;
            autoTable(doc, {
                startY, head: [['Category', 'Qty Sold', 'Revenue (UGX)', 'Profit (UGX)']],
                body: data.categories.map((c: any) => [c.name, c.qty, Number(c.revenue).toLocaleString(), Number(c.profit).toLocaleString()]),
                theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
                columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' } }
            });
            startY = (doc as any).lastAutoTable.finalY + 10;
        }

        if (data.products && data.products.length > 0) {
            doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('TOP SELLING PRODUCTS', 14, startY); startY += 2;
            autoTable(doc, {
                startY, head: [['Product', 'Qty Sold', 'Revenue (UGX)']],
                body: data.products.map((p: any) => [p.name, p.qty, Number(p.revenue).toLocaleString()]),
                theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
                columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' } }
            });
            startY = (doc as any).lastAutoTable.finalY + 10;
        }

        if (data.recentOrders && data.recentOrders.length > 0) {
            doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('RECENT SALES BREAKDOWN', 14, startY); startY += 2;
            autoTable(doc, {
                startY, head: [['Date', 'Order No', 'Customer', 'Method', 'Status', 'Amount (UGX)']],
                body: data.recentOrders.map((o: any) => [new Date(o.date).toLocaleDateString('en-GB'), o.orderNo, o.customer, o.method, o.status, Number(o.amount).toLocaleString()]),
                theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
                bodyStyles: { fontSize: 8 }, columnStyles: { 5: { halign: 'right' } }
            });
        }
    }
    else if (docRecord.report_type === 'Procurement Report') {
        const data = docRecord.report_data || {};
        
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('PROCUREMENT SUMMARY', 14, startY); startY += 2;
        autoTable(doc, {
            startY,
            head: [['Metric', 'Value (UGX)']],
            body: [
                ['Total Procurement Value', Number(data.totalValue || 0).toLocaleString()],
                ['Amount Paid', Number(data.amountPaid || 0).toLocaleString()],
                ['Balance Due', Number(data.balanceDue || 0).toLocaleString()]
            ],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
            columnStyles: { 1: { halign: 'right' } }
        });
        startY = (doc as any).lastAutoTable.finalY + 10;
        
        if (data.procurements && data.procurements.length > 0) {
            doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('PROCUREMENT BREAKDOWN', 14, startY); startY += 2;
            autoTable(doc, {
                startY, head: [['PO No', 'Date', 'Supplier', 'Status', 'Payment', 'Amount', 'Balance']],
                body: data.procurements.map((p: any) => [p.id, p.date, p.supplier, p.status, p.paymentStatus, Number(p.amount).toLocaleString(), Number(p.balance).toLocaleString()]),
                theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 2, lineWidth: { top: 0.5, bottom: 0.5 } },
                bodyStyles: { fontSize: 8 }, columnStyles: { 5: { halign: 'right' }, 6: { halign: 'right' } }
            });
        }
    }
    else if (docRecord.report_type === 'Financial Position Summary') {
        const data = docRecord.report_data || {};
        doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('MANAGEMENT SUMMARY', 14, startY); startY += 2;
        autoTable(doc, {
            startY,
            head: [['Metric', 'Amount (UGX)']],
            body: [
                ['Cash at Hand', Number(data.cashAtHand || 0).toLocaleString()],
                ['Net Mobile Money', Number(data.netMobileMoney || 0).toLocaleString()],
                ['Net Bank', Number(data.netBank || 0).toLocaleString()],
                ['Inventory Retail Value', Number(data.inventoryRetailValue || 0).toLocaleString()],
                ['Outstanding Receivables', Number(data.outstandingBalances || 0).toLocaleString()],
                ['Supplier Payables', Number(data.supplierPayables || 0).toLocaleString()],
                ['Gross Profit (All-Time)', Number(data.grossProfit || 0).toLocaleString()]
            ],
            theme: 'plain', headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 } },
            bodyStyles: { cellPadding: 2 }, columnStyles: { 1: { halign: 'right' } }
        });
    }
    else if (docRecord.report_type === 'Balance Sheet') {
        const data = docRecord.report_data || {};
        
        const cashAtHand = Number(data.cashAtHand || 0);
        const mobileMoney = Number(data.netMobileMoney || 0);
        const bankBalance = Number(data.netBank || 0);
        const accountsReceivable = Number(data.outstandingBalances || 0);
        const inventoryValue = Number(data.inventoryCostValue || 0);
        
        const totalAssets = cashAtHand + mobileMoney + bankBalance + accountsReceivable + inventoryValue;
        
        const supplierPayables = Number(data.supplierPayables || 0);
        const otherLiabilities = 0; // Future placeholder
        
        const totalLiabilities = supplierPayables + otherLiabilities;
        
        const openingFundBalance = 0; // Future placeholder
        const currentPeriodSurplus = Number(data.grossProfit || 0);
        const retainedEarnings = 0;
        
        const totalEquity = openingFundBalance + retainedEarnings + currentPeriodSurplus;
        
        // ASSETS SECTION
        doc.setFontSize(11);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(0, 0, 0);
        doc.text('ASSETS', 14, startY);
        startY += 2;
        
        autoTable(doc, {
            startY,
            head: [['Current Assets', 'Amount (UGX)']],
            body: [
                [{ content: 'Cash at Hand', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, cashAtHand.toLocaleString()],
                [{ content: 'Mobile Money Balance', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, mobileMoney.toLocaleString()],
                [{ content: 'Bank Balance', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, bankBalance.toLocaleString()],
                [{ content: 'Accounts Receivable', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, accountsReceivable.toLocaleString()],
                [{ content: 'Inventory Asset Value', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, inventoryValue.toLocaleString()]
            ],
            foot: [['Total Current Assets', totalAssets.toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], textColor: 0, cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            bodyStyles: { cellPadding: 2, textColor: 50 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 }, lineColor: [0, 0, 0] },
            columnStyles: { 1: { halign: 'right' } }
        });
        
        startY = (doc as any).lastAutoTable.finalY + 10;
        
        // LIABILITIES SECTION
        doc.setFontSize(11);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(0, 0, 0);
        doc.text('LIABILITIES', 14, startY);
        startY += 2;
        
        autoTable(doc, {
            startY,
            head: [['Current Liabilities', 'Amount (UGX)']],
            body: [
                [{ content: 'Supplier Payables', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, supplierPayables.toLocaleString()],
                [{ content: 'Other Liabilities', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, otherLiabilities.toLocaleString()]
            ],
            foot: [['Total Liabilities', totalLiabilities.toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], textColor: 0, cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            bodyStyles: { cellPadding: 2, textColor: 50 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 }, lineColor: [0, 0, 0] },
            columnStyles: { 1: { halign: 'right' } }
        });
        
        startY = (doc as any).lastAutoTable.finalY + 10;
        
        // EQUITY SECTION
        doc.setFontSize(11);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(0, 0, 0);
        doc.text('EQUITY', 14, startY);
        startY += 2;
        
        autoTable(doc, {
            startY,
            head: [['Equity Account', 'Amount (UGX)']],
            body: [
                [{ content: 'Opening Fund Balance / Equity Adjustment', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, openingFundBalance.toLocaleString()],
                [{ content: 'Retained Earnings / Accumulated Surplus', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, retainedEarnings.toLocaleString()],
                [{ content: 'Current Period Surplus (Estimated)', styles: { cellPadding: { left: 5, top: 2, bottom: 2, right: 2 } } }, currentPeriodSurplus.toLocaleString()]
            ],
            foot: [['Total Equity', totalEquity.toLocaleString()]],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [240, 240, 240], textColor: 0, cellPadding: 3, lineWidth: { top: 0.5, bottom: 0.5 }, lineColor: [200, 200, 200] },
            bodyStyles: { cellPadding: 2, textColor: 50 },
            footStyles: { fontStyle: 'bold', textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 0 }, lineColor: [0, 0, 0] },
            columnStyles: { 1: { halign: 'right' } }
        });
        
        startY = (doc as any).lastAutoTable.finalY + 15;
        
        // BALANCING SECTION
        const isBalanced = totalAssets === (totalLiabilities + totalEquity);
        const difference = totalAssets - (totalLiabilities + totalEquity);
        
        autoTable(doc, {
            startY,
            head: [['Balancing Summary', 'Amount (UGX)']],
            body: [
                ['Total Assets', totalAssets.toLocaleString()],
                ['Total Liabilities + Equity', (totalLiabilities + totalEquity).toLocaleString()],
                [{ 
                    content: isBalanced ? 'Statement Balanced' : `Statement Out of Balance (Balancing Difference: UGX ${difference.toLocaleString()})`, 
                    colSpan: 2, 
                    styles: { halign: 'center', fontStyle: 'bold', textColor: isBalanced ? [0, 128, 0] : [200, 0, 0], fillColor: isBalanced ? [240, 255, 240] : [255, 240, 240] } 
                }]
            ],
            theme: 'plain',
            headStyles: { fontStyle: 'bold', fillColor: [220, 220, 220], textColor: 0, cellPadding: 3, lineWidth: { top: 1, bottom: 1 }, lineColor: [0, 0, 0] },
            bodyStyles: { fontStyle: 'bold', cellPadding: 4, textColor: 0 },
            columnStyles: { 1: { halign: 'right' } }
        });
    } else {
        doc.text('Detailed rendering for this report type is not fully configured yet.', 14, startY);
        doc.text('Raw Data Snapshot:', 14, startY + 10);
        doc.setFont('courier', 'normal');
        doc.setFontSize(8);
        const splitText = doc.splitTextToSize(JSON.stringify(docRecord.report_data, null, 2), pageWidth - 28);
        doc.text(splitText, 14, startY + 18);
    }

    // 4. Footer & Signature Lines
    const finalY = (doc as any).lastAutoTable ? (doc as any).lastAutoTable.finalY + 20 : startY + 60;
    
    if (finalY > doc.internal.pageSize.height - 40) {
        doc.addPage();
    }
    
    const sigY = (doc as any).lastAutoTable && finalY > doc.internal.pageSize.height - 40 ? 40 : finalY;
    
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text('Prepared By:', 14, sigY);
    doc.line(14, sigY + 10, 70, sigY + 10);
    doc.text(docRecord.generated_by_name || 'System', 14, sigY + 15);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100);
    const roleText = docRecord.report_data?.generator_role || 'System Administrator';
    doc.text(roleText, 14, sigY + 19);
    doc.setTextColor(0);
    
    doc.text('Approved By:', pageWidth - 70, sigY);
    doc.line(pageWidth - 70, sigY + 10, pageWidth - 14, sigY + 10);
    doc.text('Head of Finance / Admin', pageWidth - 70, sigY + 15);

    // Page numbers and footer
    const pageCount = doc.getNumberOfPages();
    const dateGeneratedForFooter = new Date(docRecord.created_at);
    const footerDate = `${dateGeneratedForFooter.getDate().toString().padStart(2, '0')}/${(dateGeneratedForFooter.getMonth() + 1).toString().padStart(2, '0')}/${dateGeneratedForFooter.getFullYear()} ${dateGeneratedForFooter.getHours().toString().padStart(2, '0')}:${dateGeneratedForFooter.getMinutes().toString().padStart(2, '0')}`;

    for(let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(8);
        doc.setTextColor(150);
        
        // Left side timestamp
        doc.text(`Generated on ${footerDate}`, 14, doc.internal.pageSize.height - 10);
        
        // Right side page number
        doc.text(`Page ${i} of ${pageCount}`, pageWidth - 14, doc.internal.pageSize.height - 10, { align: 'right' });
    }

    return doc;
  }
};

require('dotenv').config();
const { createClient } = require('@supabase/supabase-js');
const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

async function syncIdentity(email) {
    console.log(`Synchronizing Identity for: ${email}`);

    // 1. Get the DB Identity
    const { data: dbUser, error: dbErr } = await supabase.from('users').select('id, manifest_id, role').ilike('email', email).single();
    if (dbErr || !dbUser) {
        console.error("User not found in public tables.");
        return;
    }
    console.log("Found Public UID:", dbUser.id);

    // 2. Get the GoTrue Identity
    const { data: authData } = await supabase.auth.admin.listUsers();
    const wrongAuthUser = authData.users.find(u => u.email.toLowerCase() === email.toLowerCase());

    if (wrongAuthUser && wrongAuthUser.id !== dbUser.id) {
        console.log("Removing misaligned auto-generated GoTrue identity:", wrongAuthUser.id);
        await supabase.auth.admin.deleteUser(wrongAuthUser.id);
    } else if (wrongAuthUser && wrongAuthUser.id === dbUser.id) {
        console.log("Identity is already perfectly aligned!");
        return;
    }

    // 3. Create the correctly aligned Identity
    console.log("Provisioning precise GoTrue identity...");
    const { data: newAuth, error: createErr } = await supabase.auth.admin.createUser({
        email: email,
        password: 'AutoGeneratedPlaceholderPassword123!',
        email_confirm: true
    });

    if (createErr) {
        console.error("Failed to provision:", createErr);
    } else {
        console.log("Successfully bound new Auth UID. NOW UPDATE DB ID TO MATCH THE NEW AUTH UID...");
        const newUid = newAuth.user.id;

        // Wait, postgres doesn't let us easily update a primary key if there are foreign keys, but let's try
        const { error: updateErr } = await supabase.rpc('execute_sql', {
            sql: `UPDATE users SET id = '${newUid}' WHERE email ILIKE '${email}';`
        });

        if (updateErr) {
            console.error("Failed to update public.users ID. You may need to update foreign keys manually:", updateErr);
            // Alternatively, we use the GoTrue admin to UPDATE the Auth User's ID? GoTrue doesn't support changing ID after creation via API.
        } else {
            console.log(`Successfully aligned! public.users.id is now ${newUid}`);
        }
    }
}

syncIdentity("elizabethabuo23@gmail.com");

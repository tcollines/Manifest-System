import { supabase } from '../services/supabaseClient';

export interface NextGenSoul {
    id: string;
    firstName: string;
    lastName: string;
    phone: string;
    age: number;
    gender: 'Male' | 'Female';
    residence: string;
    serviceId: string;
    status: string;
    capturedBy: string;
    notes: string;
    createdAt: string;
}

const mapFromDB = (s: any): NextGenSoul => ({
    id: s.id,
    firstName: s.first_name,
    lastName: s.last_name,
    phone: s.phone,
    age: s.age,
    gender: s.gender,
    residence: s.residence,
    serviceId: s.service_id,
    status: s.status,
    capturedBy: s.captured_by,
    notes: s.notes,
    createdAt: s.created_at
});

const mapToDB = (s: NextGenSoul) => ({
    // id generated by DB
    first_name: s.firstName,
    last_name: s.lastName,
    phone: s.phone,
    age: s.age,
    gender: s.gender,
    residence: s.residence,
    service_id: s.serviceId,
    status: s.status,
    captured_by: s.capturedBy,
    notes: s.notes
});

export const NextGenSoulsStore = {
    add: async (soul: Omit<NextGenSoul, 'id' | 'createdAt'>): Promise<void> => {
        const { error } = await supabase.from('next_gen_souls').insert([mapToDB(soul as NextGenSoul)]);
        if (error) throw error;
    },

    getAll: async (): Promise<NextGenSoul[]> => {
        const { data, error } = await supabase.from('next_gen_souls').select('*').order('created_at', { ascending: false });
        if (error) return [];
        return data.map(mapFromDB);
    },

    delete: async (id: string): Promise<void> => {
        const { error } = await supabase.from('next_gen_souls').delete().eq('id', id);
        if (error) throw error;
    },

    getByService: async (serviceId: string): Promise<NextGenSoul[]> => {
        const { data, error } = await supabase.from('next_gen_souls').select('*').eq('service_id', serviceId);
        if (error) return [];
        return data.map(mapFromDB);
    },

    getCountByService: async (serviceId: string): Promise<number> => {
        const { count, error } = await supabase
            .from('next_gen_souls')
            .select('*', { count: 'exact', head: true })
            .eq('service_id', serviceId);

        if (error) return 0;
        return count || 0;
    }
};

import { Soul } from '../types';
import { supabase } from '../services/supabaseClient';

const mapSoulFromDB = (s: any): Soul => ({
    id: s.id,
    firstName: s.first_name,
    lastName: s.last_name,
    phone: s.phone,
    email: s.email,
    gender: s.gender,
    residence: s.residence,
    status: s.status,
    sourceType: s.source_type,
    sourceId: s.source_id,
    capturedBy: s.captured_by,
    notes: s.notes,
    createdAt: s.created_at,
    preferredCallTime: s.preferred_call_time,
    studentStatus: s.student_status,
    age: s.age,
    occupation: s.occupation,
    invitedBy: s.invited_by // Assumed JSONB or structured text
});

const mapSoulToDB = (s: Soul) => ({
    // id generated by DB
    first_name: s.firstName,
    last_name: s.lastName,
    phone: s.phone,
    email: s.email,
    gender: s.gender,
    residence: s.residence,
    status: s.status,
    source_type: s.sourceType,
    source_id: s.sourceId,
    captured_by: s.capturedBy,
    notes: s.notes,
    preferred_call_time: s.preferredCallTime,
    student_status: s.studentStatus,
    age: s.age,
    occupation: s.occupation,
    invited_by: s.invitedBy // Supabase handles object -> JSONB auto conversion often, or check types
});

export const SoulsStore = {
    getAll: async (): Promise<Soul[]> => {
        try {
            const { data, error } = await supabase.from('souls').select('*').order('created_at', { ascending: false });
            if (error) {
                console.error('Error fetching souls:', error);
                return [];
            }
            return data.map(mapSoulFromDB);
        } catch (e) {
            console.error('Failed to fetch souls', e);
            return [];
        }
    },

    getBySource: async (sourceId: string): Promise<Soul[]> => {
        try {
            const { data, error } = await supabase.from('souls').select('*').eq('source_id', sourceId).order('created_at', { ascending: false });
            if (error) {
                console.error('Error fetching souls by source:', error);
                return [];
            }
            return data.map(mapSoulFromDB);
        } catch (e) {
            console.error('Failed to fetch source souls', e);
            return [];
        }
    },

    add: async (soul: Soul): Promise<void> => {
        const { error } = await supabase.from('souls').insert([mapSoulToDB(soul)]);
        if (error) throw error;
    },

    update: async (soul: Soul): Promise<void> => {
        const { error } = await supabase.from('souls').update(mapSoulToDB(soul)).eq('id', soul.id);
        if (error) throw error;
    }
};
